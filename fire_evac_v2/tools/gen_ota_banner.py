"""Generate firmware/hub_node/ota_banner.h: the "更新中" screen hub_node shows on its OLEDs during an OTA update.

python gen_ota_banner.py [font.ttc]        default C:/Windows/Fonts/msjhbd.ttc (Microsoft JhengHei Bold), needs Pillow

Same page format as EvacOled's EvacIconData.h (index = page*128 + x, bit n = row n of that page), one bitmap for
128x64 and one for 128x32. Not mirrored: people below look at the screen's front face, so text reads normally
(EvacOled's ceiling mirroring is about mapping compass directions, not about the image itself).
Also writes ota_banner_preview.png next to this script (not committed) to eyeball the result.
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "firmware", "hub_node", "ota_banner.h")
FONT = sys.argv[1] if len(sys.argv) > 1 else "C:/Windows/Fonts/msjhbd.ttc"
TEXT = "更新中"


def render(h, size):
    img = Image.new("1", (128, h), 0)
    d = ImageDraw.Draw(img)
    f = ImageFont.truetype(FONT, size)
    x0, y0, x1, y1 = d.textbbox((0, 0), TEXT, font=f)
    d.text(((128 - (x1 - x0)) // 2 - x0, (h - (y1 - y0)) // 2 - y0), TEXT, font=f, fill=1)
    if h == 64:                                   # a thin bar under the text: "busy", not a direction
        d.rectangle((24, 58, 103, 60), fill=1)
    return img


def pages(img):
    w, h = img.size
    px = img.load()
    return [sum(1 << n for n in range(8) if px[x, p * 8 + n]) for p in range(h // 8) for x in range(w)]


def c_array(name, data):
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const uint8_t {name}[{len(data)}] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def main():
    b64, b32 = render(64, 38), render(32, 28)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by fire_evac_v2/tools/gen_ota_banner.py, do not edit by hand.\n"
                f"// \"{TEXT}\" (screen's own orientation, not mirrored), SSD1306 page format: index = page*128 + x, bit n = row n.\n"
                "#pragma once\n#include <stdint.h>\n\n")
        f.write(c_array("OTA_BANNER_64", pages(b64)))
        f.write(c_array("OTA_BANNER_32", pages(b32)))
    prev = Image.new("1", (128, 100), 0)
    prev.paste(b64, (0, 0)); prev.paste(b32, (0, 68))
    prev.resize((512, 400)).save(os.path.join(HERE, "ota_banner_preview.png"))
    print("wrote", os.path.abspath(OUT))


if __name__ == "__main__":
    main()
