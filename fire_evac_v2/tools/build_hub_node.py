"""Compile hub_node with arduino-cli, with or without OTA, and keep the OTA image.

python build_hub_node.py            normal build (model in flash), same as compiling firmware/hub_node directly
                                    (both builds add 04_CameraOption=<--camera>, default ps5268: without it the SDK
                                    default JXF37 is used and the PS5268 camera does not start)
python build_hub_node.py --ota      OTA build (FQBN ...:08_OTAMode=Enable,06_LoadNNModelSource=sd); copies ota.bin to
                                    fire_evac_v2/tools/ota_out/hub_node_fw<FW>_ota.bin right after the build
options: --camera ps5268|f37  --cli PATH  --config-file PATH  --build-path PATH (short ASCII, default %TEMP%/hbn or hbo)  --dry-run

Why a script for the OTA build: the SDK's ino_validation reads the .ino as text (#if branches and comments included).
A flash build needs the default-model line, an SD build (forced by OTA) refuses any default-model line. So the
OTA build compiles a generated copy, <build-path>_sketch/hub_node_ota/hub_node_ota.ino, where that one
`ObjDet.modelSelect(... DEFAULT_YOLOV7TINY ...)` line is switched to CUSTOMIZED_YOLOV7TINY (= sd:/NN_MDL/yolov7_tiny.nb).
It also starts with `#define Arduino_OTA_MODE 1`: the SDK's boards.txt has -DArduino_OTA_MODE in build.ota_mode_flags,
but no compile recipe uses that property, so without this line every `#ifdef Arduino_OTA_MODE` would be skipped.
Everything else is the same source; ota_banner.h and a local secrets.h are copied along.
The arduino-cli config must point data at %LOCALAPPDATA%/Arduino15 (see fire_evac_v2/firmware/hub_node/README.md).
"""
import argparse, os, re, shutil, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SKETCH = os.path.join(ROOT, "fire_evac_v2", "firmware", "hub_node")
LIB = os.path.join(ROOT, "oled_fw", "libraries", "EvacOled")
FQBN = "ideasHatch:AmebaPro2:Ameba_HUB-8735_ultra"
OTA_OPTS = "08_OTAMode=Enable,06_LoadNNModelSource=sd"
LAD = os.environ.get("LOCALAPPDATA", "")
OTA_BIN = os.path.join(LAD, "Arduino15", "packages", "ideasHatch", "tools", "ameba_pro2_tools", "1.4.1", "ota.bin")
DEFAULT_LINE = "ObjDet.modelSelect(OBJECT_DETECTION, DEFAULT_YOLOV7TINY, NA_MODEL, NA_MODEL);"
SD_LINE = "ObjDet.modelSelect(OBJECT_DETECTION, CUSTOMIZED_YOLOV7TINY, NA_MODEL, NA_MODEL);   // generated: SD card model"


def ota_sketch(build_path):
    src = open(os.path.join(SKETCH, "hub_node.ino"), encoding="utf-8").read()
    if src.count(DEFAULT_LINE) != 1 or re.search(r"modelSelect\([^)]*CUSTOMIZED", src):
        sys.exit("hub_node.ino must contain exactly one default-model line and no customized one")
    out = build_path + "_sketch"
    d = os.path.join(out, "hub_node_ota")
    shutil.rmtree(out, ignore_errors=True); os.makedirs(d)
    header = ("// GENERATED by fire_evac_v2/tools/build_hub_node.py --ota from firmware/hub_node/hub_node.ino. Do not edit;\n"
              "// edit hub_node.ino and rebuild. Differences: Arduino_OTA_MODE is defined here (boards.txt has\n"
              "// -DArduino_OTA_MODE in build.ota_mode_flags, but no compile recipe uses it), and the model line reads the SD card.\n"
              "#define Arduino_OTA_MODE 1\n")
    open(os.path.join(d, "hub_node_ota.ino"), "w", encoding="utf-8", newline="\n").write(header + src.replace(DEFAULT_LINE, SD_LINE))
    for f in ("ota_banner.h", "secrets.h"):
        if os.path.exists(os.path.join(SKETCH, f)):
            shutil.copy(os.path.join(SKETCH, f), d)
    return d


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ota", action="store_true")
    ap.add_argument("--camera", default="ps5268", help="04_CameraOption value (boards.txt), default ps5268")
    ap.add_argument("--cli", default=os.path.join(ROOT, "..", "..", "..", "tools", "arduino-cli", "arduino-cli.exe"))
    ap.add_argument("--config-file", required=True)
    ap.add_argument("--build-path")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    bp = a.build_path or os.path.join(tempfile.gettempdir(), "hbo" if a.ota else "hbn")
    sketch = ota_sketch(bp) if a.ota else SKETCH
    fqbn = FQBN + ":04_CameraOption=" + a.camera + ("," + OTA_OPTS if a.ota else "")
    cmd = [a.cli, "compile", "--config-file", a.config_file, "--fqbn", fqbn, "--library", LIB, "--build-path", bp, sketch]
    print(" ".join(f'"{c}"' if " " in c else c for c in cmd), flush=True)
    if a.dry_run:
        return
    env = {k: v for k, v in os.environ.items() if not (k == "LANG" or k.startswith("LC_"))}
    before = os.path.getmtime(OTA_BIN) if os.path.exists(OTA_BIN) else 0
    r = subprocess.run(cmd, env=env)
    if r.returncode:
        sys.exit(r.returncode)
    if a.ota:
        if not os.path.exists(OTA_BIN) or os.path.getmtime(OTA_BIN) <= before:
            sys.exit(f"build ok but {OTA_BIN} was not rewritten")
        fw = re.search(r'const char\* FW = "([^"]+)"', open(os.path.join(SKETCH, "hub_node.ino"), encoding="utf-8").read()).group(1)
        os.makedirs(os.path.join(HERE, "ota_out"), exist_ok=True)
        dst = os.path.join(HERE, "ota_out", f"hub_node_fw{fw}_ota.bin")
        shutil.copy(OTA_BIN, dst)                 # the SDK overwrites ota.bin on every build: keep this one now
        print(f"ota.bin -> {dst} ({os.path.getsize(dst):,} bytes)")


if __name__ == "__main__":
    main()
